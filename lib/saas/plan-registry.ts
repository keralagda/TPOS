export class PlanRegistry {
  private static plans = new Map<string, Plan>(
    CANONICAL_PLANS.map((p) => [p.code, p])
  );

  public static getAll(): Plan[] {
    return Array.from(this.plans.values());
  }

  public static getByCode(code: string): Plan | undefined {
    return this.plans.get(code);
  }

  public static getById(id: string): Plan | undefined {
    return Array.from(this.plans.values()).find((p) => p.id === id);
  }

  /**
   * Safe versioned plan creation (immutability rule §04)
   */
  public static createNewVersion(existingCode: string, newPlanData: Partial<Plan>): Plan {
    const existing = this.getByCode(existingCode);
    if (!existing) {
      throw new Error(`Plan with code ${existingCode} not found.`);
    }

    const nextVersion = existing.version + 1;
    const newPlan: Plan = {
      ...existing,
      ...newPlanData,
      id: `plan_${existing.code.toLowerCase()}_v${nextVersion}`,
      version: nextVersion,
      updatedAt: new Date().toISOString(),
    };

    this.plans.set(newPlan.code, newPlan);
    return newPlan;
  }
}
