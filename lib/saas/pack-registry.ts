export class PackRegistry {
  private static packs = new Map<string, Pack>(
    CANONICAL_PACKS.map((p) => [p.code, p])
  );

  public static getAll(): Pack[] {
    return Array.from(this.packs.values());
  }

  public static getByCode(code: string): Pack | undefined {
    return this.packs.get(code);
  }

  public static getById(id: string): Pack | undefined {
    return Array.from(this.packs.values()).find((p) => p.id === id);
  }

  /**
   * Validate pack dependencies and detect conflicts
   */
  public static validatePackSelection(selectedCodes: string[]): {
    valid: boolean;
    missingDependencies: { pack: string; missing: string[] }[];
    conflicts: { pack: string; conflictsWith: string }[];
  } {
    const selectedSet = new Set(selectedCodes);
    const missingDependencies: { pack: string; missing: string[] }[] = [];
    const conflicts: { pack: string; conflictsWith: string }[] = [];

    for (const code of selectedCodes) {
      const pack = this.packs.get(code);
      if (!pack) continue;

      // Check dependencies
      const missing = pack.dependencies.filter((dep) => !selectedSet.has(dep));
      if (missing.length > 0) {
        missingDependencies.push({ pack: code, missing });
      }

      // Check conflicts
      for (const conflictCode of pack.conflicts) {
        if (selectedSet.has(conflictCode)) {
          conflicts.push({ pack: code, conflictsWith: conflictCode });
        }
      }
    }

    return {
      valid: missingDependencies.length === 0 && conflicts.length === 0,
      missingDependencies,
      conflicts,
    };
  }
}
